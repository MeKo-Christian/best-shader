package main

import (
	"fmt"
	"strings"
)

func emit(c *cubes, data [][4]uint32, lift, bound []float64, clusters [][][4]float64, stats []string, scale, x, z, yaw, bevel float64) string {
	var b strings.Builder
	b.WriteString("// sphere_data.glsl - generated by `just sphere` (cmd/spheregen), do not edit.\n//\n")
	for _, s := range stats {
		fmt.Fprintf(&b, "// %s\n", s)
	}
	b.WriteString("//\n// Lengths in cube edges unless noted; see cmd/spheregen for the packing.\n\n")
	fmt.Fprintf(&b, "#define SPH_N %d\n", len(data))
	fmt.Fprintf(&b, "#define SPH_FACE %d\n", c.n)
	fmt.Fprintf(&b, "#define SPH_LIFT_SEGS %d\n", len(lift)-2)
	fmt.Fprintf(&b, "const float SPH_SCALE = %.6f;     // world units per cube edge\n", scale)
	fmt.Fprintf(&b, "const vec2 SPH_POS = vec2(%.4f, %.4f); // ball centre x, z (world)\n", x, z)
	fmt.Fprintf(&b, "const float SPH_YAW = %.6f;       // ball turn about y (radians)\n", yaw)
	fmt.Fprintf(&b, "const float SPH_REST = %.6f;      // radius of the regular ball at rest\n", c.rRest)
	fmt.Fprintf(&b, "const float SPH_R0 = %.6f;        // the same, radially separable\n", c.r0)
	fmt.Fprintf(&b, "const float SPH_BEVEL = %.4f;      // edge radius\n", bevel)
	fmt.Fprintf(&b, "const float SPH_RMAX = %.1f;       // radius packing range\n", rMax)
	fmt.Fprintf(&b, "const float SPH_UA = %.4f, SPH_UB = %.4f, SPH_US = %.4f, SPH_UZ = %.4f; // phases of u\n", ua, ub, us, uz)
	fmt.Fprintf(&b, "const float SPH_SPREAD = %.4f, SPH_PACK_SPREAD = %.4f; // delays within a phase\n\n", spread, packSpread)

	b.WriteString("// quadratic B-spline control points over u: the height of the ball centre\n")
	b.WriteString("// and a radius around it that contains every cube\n")
	curve(&b, "SPH_LIFT", lift)
	curve(&b, "SPH_BOUND", bound)
	b.WriteString("\n")

	fmt.Fprintf(&b, "// bounding spheres of the %d clusters over u: B-spline control points\n", len(clusters))
	b.WriteString("// (centre xyz, radius), cluster after cluster\n")
	fmt.Fprintf(&b, "#define SPH_CL_SEGS %d\n", len(clusters[0])-2)
	b.WriteString("const vec4 SPH_CLUSTER[54 * (SPH_CL_SEGS + 2)] = vec4[](")
	for k, ctrl := range clusters {
		for j, v := range ctrl {
			if j%4 == 0 {
				b.WriteString("\n    ")
			}
			fmt.Fprintf(&b, "vec4(%.4f, %.4f, %.4f, %.4f)", v[0], v[1], v[2], v[3])
			if k < len(clusters)-1 || j < len(ctrl)-1 {
				b.WriteString(", ")
			}
		}
	}
	b.WriteString(");\n\n")

	b.WriteString("const uvec4 SPH_DATA[SPH_N] = uvec4[](")
	for i, p := range data {
		if i%2 == 0 {
			b.WriteString("\n    ")
		}
		fmt.Fprintf(&b, "uvec4(0x%08xu, 0x%08xu, 0x%08xu, 0x%08xu)", p[0], p[1], p[2], p[3])
		if i < len(data)-1 {
			b.WriteString(", ")
		}
	}
	b.WriteString(");\n")
	return b.String()
}

func curve(b *strings.Builder, name string, ctrl []float64) {
	fmt.Fprintf(b, "const float %s[SPH_LIFT_SEGS + 2] = float[](", name)
	for i, v := range ctrl {
		if i%8 == 0 {
			b.WriteString("\n    ")
		}
		fmt.Fprintf(b, "%.5f", v)
		if i < len(ctrl)-1 {
			b.WriteString(", ")
		}
	}
	b.WriteString(");\n")
}
