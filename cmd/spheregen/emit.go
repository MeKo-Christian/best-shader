package main

import (
	"fmt"
	"strings"
)

// emit writes the constants of the formula and the bounds verify() found.
func emit(p *params, s stats, lines []string, scale, hop float64, liftW int, x, z, yaw float64) string {
	var b strings.Builder
	b.WriteString("// sphere_data.glsl - generated by `just sphere` (cmd/spheregen), do not edit.\n//\n")
	for _, l := range lines {
		fmt.Fprintf(&b, "// %s\n", l)
	}
	b.WriteString("//\n// Lengths in cube edges unless noted; cmd/spheregen/formula.go explains them.\n\n")
	const pad = 0.05 // the bound holds between the samples too
	fmt.Fprintf(&b, "#define SPH_FACE %d\n", p.n)
	fmt.Fprintf(&b, "#define SPH_HOPS %d\n", p.hops)
	fmt.Fprintf(&b, "#define SPH_LIFT_W %d\n", liftW)
	fmt.Fprintf(&b, "const float SPH_SCALE = %.6f;   // world units per cube edge\n", scale)
	fmt.Fprintf(&b, "const vec2 SPH_POS = vec2(%.4f, %.4f); // ball centre x, z (world)\n", x, z)
	fmt.Fprintf(&b, "const float SPH_YAW = %.6f;     // ball turn about y (radians)\n", yaw)
	fmt.Fprintf(&b, "const float SPH_BEVEL = %.4f;    // edge radius\n", p.bevel)
	fmt.Fprintf(&b, "const float SPH_MARG = %.4f;     // clearance from the cone walls\n", p.marg)
	fmt.Fprintf(&b, "const float SPH_JITTER = %.4f;   // vertex scatter (radians)\n", p.jitter)
	fmt.Fprintf(&b, "const float SPH_WARP = %.4f;     // smooth grid distortion (radians)\n", p.warp)
	fmt.Fprintf(&b, "const float SPH_OFFSET = %.4f;   // cube offset inside its cell\n", p.offset)
	fmt.Fprintf(&b, "const float SPH_TUMBLE = %.4f;   // largest tumble (radians)\n", p.tumble)
	fmt.Fprintf(&b, "const float SPH_RREG = %.5f;    // radius of the regular ball\n", p.rReg)
	fmt.Fprintf(&b, "const float SPH_RIRR = %.4f;     // the irregular cubes sink down to this radius\n", p.rIrr)
	fmt.Fprintf(&b, "const float SPH_SINK = %.4f;     // ... and as far inside their cone fit\n", p.sink)
	fmt.Fprintf(&b, "const float SPH_RCAP = %.4f;     // narrow cells limit the tumble to stay near it\n", p.rCap)
	fmt.Fprintf(&b, "const float SPH_SPREAD = %.4f, SPH_SWEEP = %.4f; // stagger\n", p.spread, p.sweep)
	fmt.Fprintf(&b, "const float SPH_PERIOD = %.4f;   // seconds regular -> irregular -> regular\n", p.period)
	fmt.Fprintf(&b, "const float SPH_WOBBLE = %.4f, SPH_WOBROT = %.4f; // radians\n", p.wobble, p.wobRot)
	fmt.Fprintf(&b, "const float SPH_BREATH = %.4f;   // radial breathing\n", p.breath)
	fmt.Fprintf(&b, "const float SPH_RIPPLE = %.4f;   // outward ripple after a landing\n", p.ripple)
	fmt.Fprintf(&b, "const float SPH_HOP = %.4f;      // hop height (world)\n", hop)
	fmt.Fprintf(&b, "const float SPH_RHI = %.4f;      // no cube centre gets further from the ball centre\n", s.rHi+pad)
	return b.String()
}
